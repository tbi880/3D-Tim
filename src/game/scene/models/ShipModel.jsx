const FALLBACK_COLORS = Object.freeze({
    [FACTION.DAWN]: '#b9c4d0',
    [FACTION.UMBRA]: '#4a3f55',
    [FACTION.NEUTRAL]: '#8c8f96',
});

/** Ships that borrow another ship's model ({ shipModelId: modelIdItUses }). */
const MODEL_ALIASES = Object.freeze({});

/** @returns {{ file: string, size: number[], engines: number[][], scale?: number, rotation?: number[], position?: number[], exhaust?: boolean } | null} */
export function getModelInfo(modelId) {
    const id = MODEL_ALIASES[modelId] ?? modelId;
    return MODEL_OVERRIDES[id] ?? manifest[id] ?? null;
}

/** Model ids only the player flies: only the chosen one is downloaded. */
const PLAYER_MODEL_IDS = new Set(
    Object.values(SHIP_CLASSES).filter((cls) => cls.behavior === 'player').map((cls) => cls.model),
);

/** Every model file the game can show apart from the player's ships, for preloading behind the loading screen. */
export const ALL_MODEL_FILES = Object.freeze([...new Set(
    [...Object.keys(manifest), ...Object.keys(MODEL_OVERRIDES)]
        .filter((id) => !PLAYER_MODEL_IDS.has(id))
        .map((id) => getModelInfo(id).file),
)]);

/** A plain block the size of the ship, shown if its model file cannot be loaded. */
function PlaceholderHull({ size, faction }) {
    return (
        <mesh>
            <boxGeometry args={size} />
            <meshStandardMaterial color={FALLBACK_COLORS[faction] ?? FALLBACK_COLORS[FACTION.NEUTRAL]} metalness={0.4} roughness={0.5} flatShading />
        </mesh>
    );
}

/** Keeps the game playable when a model is missing (e.g. not uploaded to the bucket yet). */
export class ModelErrorBoundary extends Component {
    constructor(props) {
        super(props);
        this.state = { failed: false };
    }

    static getDerivedStateFromError() {
        return { failed: true };
    }

    render() {
        return this.state.failed ? this.props.fallback : this.props.children;
    }
}

const HULL_TEXTURE_URLS = Object.fromEntries(Object.entries(HULL_TEXTURE_FILES).map(([name, file]) => [name, bucketURL + file]));
const ROCK_TEXTURE_URLS = Object.fromEntries(Object.entries(ROCK_TEXTURE_FILES).map(([name, file]) => [name, bucketURL + file]));
/** One material set per set of loaded textures (in practice: one for the whole game). */
const materialSets = new WeakMap();

/** The ships' plating textures, set up for tiling (suspends until they are loaded). */
export function useHullTextures() {
    const textures = useTexture(HULL_TEXTURE_URLS);
    const anisotropy = useThree((state) => Math.min(8, state.gl.capabilities.getMaxAnisotropy()));
    return useMemo(() => configureSurfaceTextures(textures, anisotropy), [textures, anisotropy]);
}

/** The shared ship materials. */
export function useShipMaterials() {
    const textures = useHullTextures();
    return useMemo(() => {
        if (!materialSets.has(textures)) materialSets.set(textures, createShipMaterials(textures));
        return materialSets.get(textures);
    }, [textures]);
}

/** The asteroid surface textures, set up for tiling. */
export function useRockTextures() {
    const textures = useTexture(ROCK_TEXTURE_URLS);
    const anisotropy = useThree((state) => Math.min(8, state.gl.capabilities.getMaxAnisotropy()));
    return useMemo(() => configureSurfaceTextures(textures, anisotropy), [textures, anisotropy]);
}

/** Keeps the shared guide-light material blinking; mounted once per model that has the lights. */
function GuideLightClock({ materials }) {
    useFrame(({ clock }) => materials.setLightTime(clock.elapsedTime));
    return null;
}

function TexturedShip({ info, getThrust }) {
    const materials = useShipMaterials();
    return (
        <>
            {info.guideLights && <GuideLightClock materials={materials} />}
            {info.dockGates && <DockGates gates={info.dockGates} />}
            <GltfModel
                url={info.file}
                scale={info.scale ?? 1}
                rotation={info.rotation ?? [0, 0, 0]}
                position={info.position ?? [0, 0, 0]}
                materials={materials}
                getThrust={info.exhaust ? getThrust : null}
            />
        </>
    );
}

/**
 * The visual model of a ship, nose towards -Z, sized in metres. `getThrust` (0.15 idle ..
 * 1 full throttle .. 1.6 afterburner) drives the flames of models with their own exhaust.
 */
export default function ShipModel({ modelId, faction, getThrust = null }) {
    const info = getModelInfo(modelId);
    if (!info) return null;
    const placeholder = <PlaceholderHull size={info.size} faction={faction} />;
    return (
        <ModelErrorBoundary fallback={placeholder}>
            <Suspense fallback={null}>
                <TexturedShip info={info} getThrust={getThrust} />
            </Suspense>
        </ModelErrorBoundary>
    );
}

function PreloadOne({ file }) {
    useModelPreload(file);
    return null;
}

useTexture.preload(Object.values(HULL_TEXTURE_URLS));
useTexture.preload(Object.values(ROCK_TEXTURE_URLS));

/**
 * Downloads every ship model while the loading screen is still up, so nothing pops in
 * mid-battle. A missing file only affects that one ship (see ModelErrorBoundary).
 */
export function ShipModelPreloader() {
    // The player's ship as picked in the hangar; changing the pick downloads the new one in
    // the background (own Suspense, so the loading screen does not come back).
    const playerClass = useGameStore((state) => state.settings.playerShip);
    const playerFile = getModelInfo(SHIP_CLASSES[playerClass]?.model)?.file;
    return (
        <>
            {ALL_MODEL_FILES.map((file) => (
                <ModelErrorBoundary key={file} fallback={null}>
                    <PreloadOne file={file} />
                </ModelErrorBoundary>
            ))}
            {playerFile && (
                <ModelErrorBoundary key={playerFile} fallback={null}>
                    <Suspense fallback={null}>
                        <PreloadOne file={playerFile} />
                    </Suspense>
                </ModelErrorBoundary>
            )}
        </>
    );
}
